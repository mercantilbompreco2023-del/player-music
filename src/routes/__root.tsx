function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="pt-BR" className="dark">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();
  useEffect(() => {
    // Na abertura: contas conectadas seguem direto para reprodução;
    // visitantes veem o login, mas podem continuar sem entrar pela seta.
    if (window.location.pathname !== "/") return;
    let active = true;
    void supabase.auth.getSession().then(({ data }) => {
      if (active) void router.navigate({ to: data.session?.user ? "/player" : "/auth", replace: true });
    });
    return () => { active = false; };
  }, [router]);

  useEffect(() => {
    const { data } = supabase.auth.onAuthStateChange((event) => {
      if (event !== "SIGNED_IN" && event !== "SIGNED_OUT" && event !== "USER_UPDATED") return;
      router.invalidate();
      if (event !== "SIGNED_OUT") queryClient.invalidateQueries();
      if (event === "SIGNED_IN") {
        const next = sessionStorage.getItem("pm:after-login");
        if (next && next.startsWith("/") && !next.startsWith("//")) {
          sessionStorage.removeItem("pm:after-login");
          router.history.push(next);
        }
      }
    });
    return () => data.subscription.unsubscribe();
  }, [router, queryClient]);

  return (
    <QueryClientProvider client={queryClient}>
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <PlayerProvider>
        <AppShell>
          <Outlet />
        </AppShell>
        <Toaster position="top-center" />
      </PlayerProvider>
    </QueryClientProvider>
  );
}
